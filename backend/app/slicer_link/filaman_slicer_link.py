#!/usr/bin/env python3
"""FilaMan Slicer-Link: reports a freshly sliced job to FilaMan.

Use it as a post-processing script of PrusaSlicer, SuperSlicer, OrcaSlicer or
BambuStudio (or call it by hand for Cura). The slicer appends the G-code path
as the last argument:

    python filaman_slicer_link.py --url https://filaman.local --key <API-KEY> \
        --printer <ID> [--map 0=1,1=2] [--test] <gcode-path>

Only the Python standard library is used (Python 3.8+). The script never fails
the slicing run: every error goes to ~/.filaman_slicer_link.log and the exit
code is always 0.
"""

import argparse
import json
import os
import re
import sys
import traceback
import urllib.error
import urllib.request
from datetime import datetime

SCRIPT_VERSION = "1.0.0"

TIMEOUT_S = 10
LOG_PATH = os.path.join(os.path.expanduser("~"), ".filaman_slicer_link.log")
LOG_MAX_BYTES = 256 * 1024
# Slicers write their statistics either at the top or at the bottom of the file.
SCAN_BYTES = 1024 * 1024


# ----------------------------------------------------------------- logging


def log(message):
    try:
        try:
            if os.path.getsize(LOG_PATH) > LOG_MAX_BYTES:
                os.remove(LOG_PATH)
        except OSError:
            pass
        with open(LOG_PATH, "a", encoding="utf-8", errors="replace") as handle:
            handle.write("%s %s\n" % (datetime.now().isoformat(timespec="seconds"), message))
    except Exception:  # noqa: BLE001 - logging must never break slicing
        pass


# ----------------------------------------------------------------- parsing


def _read_comment_lines(path):
    """Comment lines of the head and tail of a G-code file (utf-8, lossy)."""
    size = os.path.getsize(path)
    with open(path, "rb") as handle:
        if size <= 2 * SCAN_BYTES:
            chunks = [handle.read()]
        else:
            head = handle.read(SCAN_BYTES)
            handle.seek(size - SCAN_BYTES)
            chunks = [head, handle.read()]
    lines = []
    head_lines = set()
    for number, chunk in enumerate(chunks):
        text = chunk.decode("utf-8", errors="replace")
        found = [line.strip() for line in text.splitlines() if line.lstrip().startswith(";")]
        if number == 0:
            head_lines = set(found)
        else:
            # A line in both head and tail is one block, not two (dual nozzle sums stay intact).
            found = [line for line in found if line not in head_lines]
        lines.extend(found)
    return lines


_KV = re.compile(r"^;\s*([A-Za-z0-9_ ()\[\]/.\-]+?)\s*[=:]\s*(.*)$")


def _numbers(text):
    """All numbers of a comma or semicolon separated list (None for gaps)."""
    values = []
    for part in re.split(r"[,;]", text):
        part = part.strip()
        if not part:
            continue
        match = re.match(r"^-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", part)
        values.append(float(match.group(0)) if match else None)
    return values


def _add_lists(lists):
    """Element-wise sum of several number lists (dual nozzle, repeated blocks)."""
    width = max((len(item) for item in lists), default=0)
    total = []
    for i in range(width):
        total.append(sum((item[i] or 0.0) for item in lists if i < len(item)))
    return total


def parse_duration(text):
    """'1d 2h 3m 4s' (any subset) to seconds, or None."""
    parts = re.findall(r"(\d+(?:\.\d+)?)\s*([dhms])", text)
    if not parts:
        return None
    factor = {"d": 86400, "h": 3600, "m": 60, "s": 1}
    return int(round(sum(float(value) * factor[unit] for value, unit in parts)))


def _norm_color(value):
    value = (value or "").strip()
    match = re.match(r"^#?([0-9A-Fa-f]{6})(?:[0-9A-Fa-f]{2})?$", value)
    return "#" + match.group(1).upper() if match else None


def _split_list(value):
    return [part.strip().strip('"') for part in re.split(r"[;,]", value) if part.strip()]


def parse_gcode_lines(lines):
    """Extract slicer, filaments and print time from G-code comment lines."""
    grams, mm, total_g = [], [], []
    cura_mm = []
    info = {}
    time_s = {}
    name = None
    for line in lines:
        cura = re.match(r"^;\s*Filament used:\s*(.*)$", line, re.I)
        if cura:
            cura_mm.append([(v * 1000.0 if v is not None else None) for v in _numbers(cura.group(1))])
            continue
        cura_time = re.match(r"^;\s*(?:PRINT\.)?TIME:\s*(\d+(?:\.\d+)?)", line)
        if cura_time:
            time_s.setdefault("cura", int(float(cura_time.group(1))))
            continue
        flavor = re.match(r"^;\s*Generated with Cura_SteamEngine\s*(\S*)", line)
        if flavor:
            info["slicer"] = "Cura"
            info["slicer_version"] = flavor.group(1) or None
            continue
        generated = re.match(
            r"^;\s*generated by\s+(PrusaSlicer|SuperSlicer|OrcaSlicer|Orca Slicer|BambuStudio|Bambu Studio)\s*([^\s]*)",
            line,
            re.I,
        )
        if generated:
            info["slicer"] = generated.group(1).replace(" ", "")
            info["slicer_version"] = generated.group(2) or None
            continue
        bambu_header = re.match(r"^;\s*BambuStudio\s+([\d.]+)", line)
        if bambu_header:
            info.setdefault("slicer", "BambuStudio")
            info.setdefault("slicer_version", bambu_header.group(1))
            continue

        match = _KV.match(line)
        if not match:
            continue
        key = re.sub(r"\s+", " ", match.group(1).strip().lower())
        value = match.group(2).strip()
        if key == "filament used [g]":
            grams.append(_numbers(value))
        elif key == "filament used [mm]":
            mm.append(_numbers(value))
        elif key in ("total filament used [g]", "total filament weight [g]"):
            numbers = _numbers(value)
            if numbers and numbers[0] is not None:
                total_g.append(numbers[0])
        elif key == "estimated printing time (normal mode)":
            time_s.setdefault("normal", parse_duration(value))
        elif key == "total estimated time":
            time_s.setdefault("total", parse_duration(value))
        elif key == "model printing time":
            # Bambu: "model printing time: 1h 2m; total estimated time: 1h 5m"
            time_s.setdefault("model", parse_duration(value.split(";")[0]))
            total = re.search(r"total estimated time\s*[:=]\s*([^;]+)", value)
            if total:
                time_s.setdefault("total", parse_duration(total.group(1)))
        elif key == "filament_type":
            info["types"] = _split_list(value)
        elif key == "filament_colour":
            info["colors"] = [_norm_color(item) for item in _split_list(value)]
        elif key == "printer_model":
            info["printer_model"] = value.strip('"') or None
        elif key in ("model name", "plate name", "plate_name", "object name"):
            name = name or value.strip('"') or None

    weights = _add_lists(grams) if grams else []
    lengths = _add_lists(mm) if mm else (_add_lists(cura_mm) if cura_mm else [])
    count = max(len(weights), len(lengths))
    if count == 0 and total_g:
        weights, count = [total_g[0]], 1

    filaments = []
    types = info.get("types") or []
    colors = info.get("colors") or []
    for index in range(count):
        weight = weights[index] if index < len(weights) else None
        length = lengths[index] if index < len(lengths) else None
        if not (weight or 0) > 0 and not (length or 0) > 0:
            continue
        entry = {"index": index}
        if weight and weight > 0:
            entry["weight_g"] = round(weight, 3)
        if length and length > 0:
            entry["length_mm"] = round(length, 1)
        if index < len(types) and types[index]:
            entry["material"] = types[index]
        if index < len(colors) and colors[index]:
            entry["color_hex"] = colors[index]
        filaments.append(entry)

    print_time = time_s.get("total") or time_s.get("model") or time_s.get("normal") or time_s.get("cura")
    if "slicer" not in info:
        info["slicer"] = "Cura" if cura_mm else "unknown"
    return {
        "filaments": filaments,
        "print_time_s": print_time,
        "slicer": info.get("slicer"),
        "slicer_version": info.get("slicer_version"),
        "printer_model": info.get("printer_model"),
        "model_name": name,
    }


def parse_gcode_file(path):
    return parse_gcode_lines(_read_comment_lines(path))


def _is_temp_name(stem):
    return bool(re.match(r"^(?:\d+|[0-9a-f]{16,}|tmp\w*|temp\w*)$", stem, re.I))


def job_name(path, parsed=None, environ=None):
    environ = os.environ if environ is None else environ
    for candidate in (environ.get("SLIC3R_PP_OUTPUT_NAME"), path):
        if not candidate:
            continue
        stem = os.path.splitext(os.path.basename(candidate))[0].strip()
        if stem and not _is_temp_name(stem):
            return stem
    model = (parsed or {}).get("model_name")
    if model:
        return model
    stem = os.path.splitext(os.path.basename(path or ""))[0].strip()
    return stem or "Slicer job"


# ----------------------------------------------------------------- network


def parse_map(text):
    result = {}
    for part in (text or "").split(","):
        if "=" not in part:
            continue
        left, right = part.split("=", 1)
        try:
            result[int(left.strip())] = int(right.strip())
        except ValueError:
            log("Ignoring invalid --map entry %r" % part)
    return result


def _request(base_url, key, path, payload):
    url = base_url.rstrip("/") + "/api/v1/slicer-link/" + path
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=body,
        method="POST",
        headers={
            "Content-Type": "application/json",
            "Authorization": "ApiKey " + key.strip(),
            "User-Agent": "filaman-slicer-link/" + SCRIPT_VERSION,
        },
    )
    with urllib.request.urlopen(request, timeout=TIMEOUT_S) as response:
        return json.loads(response.read().decode("utf-8", errors="replace") or "{}")


def _describe_error(exc):
    if isinstance(exc, urllib.error.HTTPError):
        try:
            detail = exc.read().decode("utf-8", errors="replace")[:300]
        except Exception:  # noqa: BLE001
            detail = ""
        return "HTTP %s %s" % (exc.code, detail)
    return "%s: %s" % (type(exc).__name__, exc)


def run_test(args):
    try:
        data = _request(args.url, args.key, "ping", {"printer_id": args.printer, "script_version": SCRIPT_VERSION})
    except Exception as exc:  # noqa: BLE001
        message = "FilaMan Slicer-Link: connection FAILED (%s)" % _describe_error(exc)
        log(message)
        print(message)
        return
    message = "FilaMan Slicer-Link: connection OK (script %s)" % SCRIPT_VERSION
    if data.get("update_available"):
        message += " - a newer script %s is available" % data.get("latest_script_version")
    log(message)
    print(message)


def run_job(args):
    path = args.gcode
    if not path or not os.path.isfile(path):
        log("G-code file not found: %r" % path)
        return
    parsed = parse_gcode_file(path)
    if not parsed["filaments"]:
        log("No filament usage found in %s, nothing sent" % path)
        return
    payload = {
        "printer_id": args.printer,
        "job_name": job_name(path, parsed),
        "slicer": parsed["slicer"] or "unknown",
        "slicer_version": parsed["slicer_version"],
        "print_time_s": parsed["print_time_s"],
        "filaments": parsed["filaments"],
        "script_version": SCRIPT_VERSION,
    }
    mapping = parse_map(args.map)
    if mapping:
        payload["slot_map"] = {str(k): v for k, v in mapping.items()}
    data = _request(args.url, args.key, "jobs", payload)
    log("Sent job %r -> FilaMan job #%s" % (payload["job_name"], data.get("job_id")))
    if data.get("update_available"):
        log("A newer Slicer-Link script %s is available" % data.get("latest_script_version"))


def build_parser():
    parser = argparse.ArgumentParser(description="Report a sliced job to FilaMan")
    parser.add_argument("--url", default=os.environ.get("FILAMAN_URL"))
    parser.add_argument("--key", default=os.environ.get("FILAMAN_API_KEY"))
    parser.add_argument("--printer", type=int)
    parser.add_argument("--map", default="")
    parser.add_argument("--test", action="store_true")
    parser.add_argument("gcode", nargs="?")
    return parser


def main(argv=None):
    try:
        parser = build_parser()
        try:
            args, _unknown = parser.parse_known_args(argv)
        except SystemExit:
            log("Invalid arguments: %r" % (argv if argv is not None else sys.argv[1:]))
            return 0
        if not args.url or not args.key:
            log("--url and --key (or FILAMAN_API_KEY) are required")
            if args.test:
                print("FilaMan Slicer-Link: --url and --key are required")
            return 0
        if args.test:
            run_test(args)
        else:
            run_job(args)
    except Exception as exc:  # noqa: BLE001 - never break the slicing run
        log("Error: %s\n%s" % (_describe_error(exc), traceback.format_exc()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
